GRANT ROLE JEV_LAB_ANALYST TO USER IDENTIFIER($participant_user);
GRANT ROLE JEV_LAB_ML TO USER IDENTIFIER($participant_user);
GRANT ROLE JEV_LAB_CONSUMER TO USER IDENTIFIER($participant_user);
GRANT USAGE ON WAREHOUSE IDENTIFIER($lab_wh) TO ROLE JEV_LAB_STEWARD;
GRANT USAGE ON WAREHOUSE IDENTIFIER($lab_wh) TO ROLE JEV_LAB_ANALYST;
GRANT USAGE ON WAREHOUSE IDENTIFIER($lab_wh) TO ROLE JEV_LAB_ML;
