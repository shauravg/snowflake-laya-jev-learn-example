USE SECONDARY ROLES NONE;
USE DATABASE IDENTIFIER($lab_db);
CREATE SCHEMA RAW;
CREATE SCHEMA GOVERNANCE;
CREATE SCHEMA CURATED;
CREATE SCHEMA ML;
GRANT USAGE ON DATABASE IDENTIFIER($lab_db) TO ROLE JEV_LAB_ANALYST;
GRANT USAGE ON DATABASE IDENTIFIER($lab_db) TO ROLE JEV_LAB_ML;
GRANT USAGE ON DATABASE IDENTIFIER($lab_db) TO ROLE JEV_LAB_CONSUMER;
GRANT USAGE ON SCHEMA RAW TO ROLE JEV_LAB_ANALYST;
GRANT USAGE ON SCHEMA CURATED TO ROLE JEV_LAB_ML;
GRANT USAGE ON SCHEMA CURATED TO ROLE JEV_LAB_CONSUMER;
GRANT USAGE ON SCHEMA ML TO ROLE JEV_LAB_ML;
GRANT USAGE ON SCHEMA ML TO ROLE JEV_LAB_CONSUMER;
GRANT CREATE MODEL, CREATE SERVICE, CREATE IMAGE REPOSITORY,
      CREATE STAGE, CREATE TABLE, CREATE VIEW, CREATE EXPERIMENT ON SCHEMA ML TO ROLE JEV_LAB_ML;
