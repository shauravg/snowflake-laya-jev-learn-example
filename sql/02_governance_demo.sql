-- Run 00_config.sql first. Policies require a supported Snowflake edition.
USE ROLE JEV_LAB_STEWARD;
USE SECONDARY ROLES NONE;
USE DATABASE IDENTIFIER($lab_db);
USE SCHEMA GOVERNANCE;
CREATE MASKING POLICY IDENTITY_MASK AS (value STRING) RETURNS STRING ->
  IFF(IS_ROLE_IN_SESSION('JEV_LAB_STEWARD'), value, '[REDACTED]');
CREATE MASKING POLICY MESSAGE_MASK AS (value STRING) RETURNS STRING ->
  IFF(IS_ROLE_IN_SESSION('JEV_LAB_STEWARD'), value, '[RESTRICTED MESSAGE]');
CREATE MASKING POLICY JSON_MASK AS (value VARIANT) RETURNS VARIANT ->
  IFF(IS_ROLE_IN_SESSION('JEV_LAB_STEWARD'), value, TO_VARIANT('[RESTRICTED JSON]'));
CREATE MASKING POLICY TAG_MASK AS (value ARRAY) RETURNS ARRAY ->
  IFF(IS_ROLE_IN_SESSION('JEV_LAB_STEWARD'), value, ARRAY_CONSTRUCT());
CREATE ROW ACCESS POLICY SUPPORT_REGION AS (region STRING) RETURNS BOOLEAN ->
  IS_ROLE_IN_SESSION('JEV_LAB_STEWARD') OR
  (IS_ROLE_IN_SESSION('JEV_LAB_ANALYST') AND region = 'WEST');

ALTER TABLE RAW.ZENDESK_USERS MODIFY COLUMN name SET MASKING POLICY IDENTITY_MASK;
ALTER TABLE RAW.ZENDESK_USERS MODIFY COLUMN email SET MASKING POLICY IDENTITY_MASK;
ALTER TABLE RAW.ZENDESK_USERS MODIFY COLUMN phone SET MASKING POLICY IDENTITY_MASK;
ALTER TABLE RAW.ZENDESK_USERS MODIFY COLUMN user_fields SET MASKING POLICY JSON_MASK;
ALTER TABLE RAW.ZENDESK_ORGANIZATIONS MODIFY COLUMN name SET MASKING POLICY IDENTITY_MASK;
ALTER TABLE RAW.ZENDESK_ORGANIZATIONS MODIFY COLUMN organization_fields SET MASKING POLICY JSON_MASK;
ALTER TABLE RAW.ZENDESK_TICKETS MODIFY COLUMN subject SET MASKING POLICY MESSAGE_MASK;
ALTER TABLE RAW.ZENDESK_TICKETS MODIFY COLUMN description SET MASKING POLICY MESSAGE_MASK;
ALTER TABLE RAW.ZENDESK_TICKETS MODIFY COLUMN custom_fields SET MASKING POLICY TAG_MASK;
ALTER TABLE RAW.ZENDESK_TICKETS MODIFY COLUMN tags SET MASKING POLICY TAG_MASK;
ALTER TABLE RAW.ZENDESK_TICKET_COMMENTS MODIFY COLUMN body SET MASKING POLICY MESSAGE_MASK;
ALTER TABLE TRIAGE_INPUT_SNAPSHOTS MODIFY COLUMN subject SET MASKING POLICY MESSAGE_MASK;
ALTER TABLE TRIAGE_INPUT_SNAPSHOTS MODIFY COLUMN description SET MASKING POLICY MESSAGE_MASK;

-- No analyst SELECT on raw tables, snapshots, arbitrary JSON, or comments.
-- Separate safe views avoid claiming a ticket's row policy protects child comments.
CREATE SECURE VIEW RAW.ANALYST_USERS AS
SELECT u.id, u.name, u.email, u.phone, g.region
FROM RAW.ZENDESK_USERS u JOIN GOVERNANCE.REQUESTER_SCOPE g ON g.requester_id=u.id;
ALTER VIEW RAW.ANALYST_USERS ADD ROW ACCESS POLICY SUPPORT_REGION ON (region);
CREATE SECURE VIEW RAW.ANALYST_TICKETS AS
SELECT t.id, t.type, t.priority, t.status, g.region
FROM RAW.ZENDESK_TICKETS t JOIN GOVERNANCE.REQUESTER_SCOPE g ON g.requester_id=t.requester_id;
ALTER VIEW RAW.ANALYST_TICKETS ADD ROW ACCESS POLICY SUPPORT_REGION ON (region);
GRANT SELECT ON VIEW RAW.ANALYST_USERS TO ROLE JEV_LAB_ANALYST;
GRANT SELECT ON VIEW RAW.ANALYST_TICKETS TO ROLE JEV_LAB_ANALYST;

SELECT * FROM RAW.ANALYST_USERS ORDER BY id LIMIT 5;
